/** `count` rows, each distinguishable by ring number. */
export function makeDemonRows(count: number, overrides: Partial<DemonRow> = {}) {
	return Array.from({ length: count }, (_, rowIndex) =>
		makeDemonRow({
			ring_no: `A${rowIndex.toString().padStart(6, '0')}`,
			...overrides
		})
	);
}
